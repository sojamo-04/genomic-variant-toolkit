"""VCF and NGS Variant Parser for Targeted Sequencing Panels.

Extracts quality control metrics, SNVs, CNVs, and structural variants from
VCFv4.1 files.
"""

import json
from pathlib import Path
from typing import Any, Dict, List, Optional


def safe_float(value: Optional[str]) -> Optional[float]:
  if value is None or value in ('.', ''):
    return None
  try:
    return float(value)
  except (ValueError, TypeError):
    return None


def safe_int(value: Optional[str]) -> Optional[int]:
  if value is None or value in ('.', ''):
    return None
  try:
    return int(float(value))
  except (ValueError, TypeError):
    return None


class VCFParser:
  """Parses targeted sequencing VCF files generated by Torrent Variant Caller."""

  def __init__(self, vcf_path: Path):
    self.vcf_path = Path(vcf_path)
    self.header_info: Dict[str, Any] = {}

  def parse_header(self) -> Dict[str, Any]:
    """Extracts run-level QC metrics and metadata from VCF header lines."""
    with open(self.vcf_path, 'r', encoding='utf-8') as f:
      for line in f:
        if not line.startswith('##'):
          if line.startswith('#CHROM'):
            break
          continue

        line_clean = line.strip()[2:]
        if '=' not in line_clean:
          continue

        key, value = line_clean.split('=', 1)

        if key in ('sampleGender', 'AssumedGender'):
          self.header_info['gender'] = value
        elif key == 'mapd':
          self.header_info['mapd'] = safe_float(value)
        elif key == 'median_reads_per_amplicon':
          self.header_info['median_reads_per_amplicon'] = safe_float(value)
        elif key == 'TotalMappedFusionPanelReads':
          self.header_info['total_fusion_reads'] = safe_int(value)
        elif key == 'FusionSampleQC':
          self.header_info['fusion_qc'] = value.split(',')[0].strip().upper()
        elif key == 'IonReporterWorkflowName':
          self.header_info['workflow'] = value

    return self.header_info

  def parse_variants(self) -> Dict[str, List[Dict[str, Any]]]:
    """Parses variant records, categorizing them into mutations, CNVs, and RNA alterations."""
    mutations = []
    cnvs = []
    rna_variants = []

    with open(self.vcf_path, 'r', encoding='utf-8') as f:
      for line in f:
        if line.startswith('#'):
          continue

        fields = line.strip().split('\t')
        if len(fields) < 10:
          continue

        (
            chrom,
            pos,
            var_id,
            ref,
            alt,
            qual,
            filter_val,
            info_str,
            format_str,
            sample,
        ) = fields[:10]

        info_dict = {}
        for item in info_str.split(';'):
          if '=' in item:
            k, v = item.split('=', 1)
            info_dict[k] = v
          else:
            info_dict[item] = True

        format_keys = format_str.split(':')
        format_values = sample.split(':')
        format_dict = dict(zip(format_keys, format_values))

        func = {}
        if 'FUNC' in info_dict:
          try:
            func_str = info_dict['FUNC'].replace("'", '"')
            func_data = json.loads(func_str)
            func = (
                func_data[0] if isinstance(func_data, list) else func_data
            )
          except Exception:
            func = {}

        svtype = info_dict.get('SVTYPE', '')

        if svtype == 'CNV':
          cnvs.append({
              'gene': func.get('gene') or var_id or '',
              'chrom': chrom,
              'pos': safe_int(pos),
              'end': safe_int(info_dict.get('END')),
              'cn': safe_float(format_dict.get('CN')),
              'ci': info_dict.get('CI', ''),
              'filter': filter_val,
          })
        elif svtype in ('Fusion', 'RNAExonTiles', 'RNAExonVariant'):
          rna_variants.append({
              'id': var_id if var_id != '.' else '',
              'svtype': svtype,
              'read_count': safe_int(info_dict.get('READ_COUNT')),
              'mol_count': safe_int(info_dict.get('MOL_COUNT')),
          })
        else:
          af = safe_float(info_dict.get('AF'))
          dp = safe_int(info_dict.get('FDP')) or safe_int(info_dict.get('DP'))
          mutations.append({
              'gene': func.get('gene', ''),
              'protein': func.get('protein', ''),
              'coding': func.get('coding', ''),
              'chrom': chrom,
              'pos': safe_int(pos),
              'ref': ref,
              'alt': alt,
              'af': af,
              'dp': dp,
              'filter': filter_val,
          })

    return {'mutations': mutations, 'cnvs': cnvs, 'rna': rna_variants}
